    function toggleLanguageDropdown(event) {
  event.stopPropagation();
  const dropdown = event.currentTarget.parentElement;
  dropdown.classList.toggle('active');
}

function selectLanguage(lang, event) {
  if (event) {
    event.preventDefault();
    event.stopPropagation();
  }
 
  localStorage.setItem('selectedLanguage', lang);
  applyLanguage(lang);
 
  const dropdowns = document.querySelectorAll('.language-dropdown');
  dropdowns.forEach(d => d.classList.remove('active'));
 
  const currentLangDisplay = document.getElementById('currentLanguage');
  if (currentLangDisplay) {
    currentLangDisplay.textContent = languageNames[lang] || lang.toUpperCase();
  }
}

function applyLanguage(lang) {
  const t = translations[lang];
  if (!t) return;
 
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (t[key]) {
      const hasChildElements = element.querySelector('span, strong, em, b, i');
      if (hasChildElements) {
        const textNodes = [];
        const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT, null, false);
        let node;
        while (node = walker.nextNode()) {
          textNodes.push(node);
        }
        if (textNodes.length > 0) {
          if (!element.closest('a') && !element.closest('button')) {
            textNodes[0].textContent = t[key];
          } else {
            element.textContent = t[key];
          }
        } else {
          element.textContent = t[key];
        }
      } else {
        element.textContent = t[key];
      }
    }
  });
 
  document.querySelectorAll('[data-i18n-html]').forEach(element => {
    const key = element.getAttribute('data-i18n-html');
    if (t[key]) {
      element.innerHTML = t[key];
    }
  });
 
  document.documentElement.lang = lang;
}

document.addEventListener('DOMContentLoaded', function() {
  const savedLang = localStorage.getItem('selectedLanguage') || 'en';
 
  if (translations[savedLang]) {
    applyLanguage(savedLang);
    const currentLangDisplay = document.getElementById('currentLanguage');
    if (currentLangDisplay) {
      currentLangDisplay.textContent = languageNames[savedLang] || savedLang.toUpperCase();
    }
  } else {
    applyLanguage('en');
    const currentLangDisplay = document.getElementById('currentLanguage');
    if (currentLangDisplay) {
      currentLangDisplay.textContent = 'English';
    }
  }
 
  document.addEventListener('click', function(e) {
    const dropdowns = document.querySelectorAll('.language-dropdown');
    dropdowns.forEach(dropdown => {
      if (!dropdown.contains(e.target)) {
        dropdown.classList.remove('active');
      }
    });
  });
});